#define USE_FSR

__global__ void upscale(KittlesPT::DeviceTextureBuffer t_src, KittlesPT::DeviceTextureBuffer t_dst)
{
	using namespace KittlesPT;

	ShadingJob shading_job = getShadingJob(t_dst.dimensions);

	if (shading_job.is_invalid) {
		return;
	}
	float4 data;

#ifdef USE_FSR
	float3 c;
	float4 con0, con1, con2, con3;
	// "rendersize" refers to size of source image before upscaling.
	float2 rendersize = make_float2(t_src.dimensions);
	FsrEasuCon(
		con0, con1, con2, con3,
		rendersize, rendersize, make_float2(t_dst.dimensions)
	);
	FsrEasuF(c, make_float2(shading_job.pixel_coord),
		con0, con1, con2, con3, t_src);
	data = make_float4(c, 1);
#else
	float2 dst_uv = make_float2(shading_job.pixel_coord) / t_dst.dimensions;
	float2 src_pixel_coord = dst_uv * t_src.dimensions;

	data = t_src.textureReadBilinear(src_pixel_coord, true);
#endif // USE_FSR

	t_dst.textureWrite(data, shading_job.pixel_coord);
}

